/**
 * Generates packages/ui/logos.ts from apps/web/public/company-logos/manifest.json.
 * Run: pnpm --filter @aroma/ui gen:logos. A test fails when the committed file is stale.
 * The manifest is the provenance record (source URLs, hashes); this keeps one line per logo.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

interface ManifestLogo {
  issuer: string;
  symbol: string;
  underlyingSymbol: string;
  mints: string[];
  file: string;
}
interface Manifest {
  logos: ManifestLogo[];
}

const here = dirname(fileURLToPath(import.meta.url));
export const LOGO_DIR = resolve(here, "../../../apps/web/public/company-logos");
export const OUTPUT_FILE = resolve(here, "../logos.ts");

/** Pure: builds the file text, throwing if the manifest and the directory disagree. */
export function buildLogosSource(
  manifest: Manifest,
  filesOnDisk: readonly string[],
): string {
  const listed = new Set(manifest.logos.map((logo) => logo.file));
  const missing = [...listed].filter((file) => !filesOnDisk.includes(file));
  if (missing.length)
    throw new Error(
      `manifest lists files that do not exist: ${missing.join(", ")}`,
    );
  const orphans = filesOnDisk.filter(
    (file) => file.endsWith(".webp") && !listed.has(file),
  );
  if (orphans.length)
    throw new Error(
      `webp files missing from manifest.json: ${orphans.join(", ")}`,
    );
  const mints = manifest.logos.flatMap((logo) => logo.mints);
  const duplicate = mints.find((mint, index) => mints.indexOf(mint) !== index);
  if (duplicate) throw new Error(`mint listed twice in manifest: ${duplicate}`);

  const rows = [...manifest.logos]
    .sort((a, b) =>
      `${a.issuer}:${a.symbol}`.localeCompare(`${b.issuer}:${b.symbol}`),
    )
    .map(
      (logo) =>
        `  { issuer: ${JSON.stringify(logo.issuer)}, symbol: ${JSON.stringify(logo.symbol)}, underlyingSymbol: ${JSON.stringify(logo.underlyingSymbol)}, file: ${JSON.stringify(logo.file)}, mints: ${JSON.stringify(logo.mints)} },`,
    );
  return [
    "// GENERATED by scripts/gen-logos.ts from apps/web/public/company-logos/manifest.json.",
    "// Do not edit by hand: run `pnpm --filter @aroma/ui gen:logos`. Provenance: that manifest.",
    "",
    "export interface CompanyLogoEntry {",
    "  readonly issuer: string;",
    "  readonly symbol: string;",
    "  readonly underlyingSymbol: string;",
    "  readonly file: string;",
    "  readonly mints: readonly string[];",
    "}",
    "",
    "/** URL path the logo files are served from (apps/web/public). */",
    'export const COMPANY_LOGO_BASE_PATH = "/company-logos";',
    "",
    "export const companyLogos: readonly CompanyLogoEntry[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

export function readSources(dir = LOGO_DIR): {
  manifest: Manifest;
  files: string[];
} {
  const manifest = JSON.parse(
    readFileSync(join(dir, "manifest.json"), "utf8"),
  ) as Manifest;
  return { manifest, files: readdirSync(dir) };
}

function main(): void {
  if (!existsSync(LOGO_DIR))
    throw new Error(`logo directory not found: ${LOGO_DIR}`);
  const { manifest, files } = readSources();
  writeFileSync(OUTPUT_FILE, buildLogosSource(manifest, files));
  console.warn(`wrote ${OUTPUT_FILE} (${manifest.logos.length} logos)`);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
