// Renders the v1 TypeScript client from the Anchor IDL with Codama, into this package
// (`src/v1/generated`). `packages/contracts/scripts/sync-idl.mjs` copies the built IDL here and
// calls `renderClient`; the drift test (`src/v1/drift.test.ts`) calls `generatedDrift`.
// Renderer pinned at @codama/renderers-js 2.4.0: the last release whose output targets kit 6.x
// APIs; its output typechecks (strict, noUncheckedIndexedAccess) and runs against the
// workspace's @solana/kit 7.1.1. 2.5.0 and later target kit ^8.3. `rootOnly` imports use
// `@solana/kit` and its `@solana/kit/program-client-core` subpath, so the web app needs no new
// dependency.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createFromRoot } from "codama";
import { rootNodeFromAnchor } from "@codama/nodes-from-anchor";
import { renderVisitor } from "@codama/renderers-js";

const packageRoot = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  "..",
);
export const COMMITTED_IDL = path.join(
  packageRoot,
  "src/v1/idl/aroma_guard.json",
);
export const GENERATED = path.join(packageRoot, "src/v1/generated");

export const HEADER =
  "// GENERATED by packages/contracts/scripts/codama.mjs from the v1 IDL. Do not edit; run `pnpm --filter @aroma/contracts idl:sync`.\n";

/** Renders `idl` into `outDir` (replaced). Every file starts with the GENERATED header. */
export async function renderClient(idl, outDir) {
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), "aroma-codama-"));
  try {
    const codama = createFromRoot(rootNodeFromAnchor(idl));
    await codama.accept(
      renderVisitor(staging, {
        kitImportStrategy: "rootOnly",
        syncPackageJson: false,
      }),
    );
    const generated = path.join(staging, "src", "generated");
    fs.rmSync(outDir, { recursive: true, force: true });
    for (const file of listFiles(generated)) {
      const target = path.join(outDir, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(
        target,
        HEADER + fs.readFileSync(path.join(generated, file), "utf8"),
      );
    }
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
}

export function listFiles(dir, prefix = "") {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? listFiles(path.join(dir, entry.name), path.join(prefix, entry.name))
        : [path.join(prefix, entry.name)],
    )
    .sort();
}

/** Lists files that differ, are missing or are extra between two directories. */
export function diffDirs(expected, actual) {
  const a = listFiles(expected),
    b = listFiles(actual);
  const all = [...new Set([...a, ...b])].sort();
  return all.filter((file) => {
    const x = path.join(expected, file),
      y = path.join(actual, file);
    return (
      !fs.existsSync(x) ||
      !fs.existsSync(y) ||
      !fs.readFileSync(x).equals(fs.readFileSync(y))
    );
  });
}

/** Files where the committed client differs from a fresh render of `idlPath`. */
export async function generatedDrift(
  idlPath = COMMITTED_IDL,
  generatedDir = GENERATED,
) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "aroma-drift-"));
  try {
    await renderClient(JSON.parse(fs.readFileSync(idlPath, "utf8")), tmp);
    return diffDirs(tmp, generatedDir);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}
